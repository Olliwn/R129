def draw_dot_text(p: QPainter, x: float, y: float, text: str,
                  on_color: QColor = None, scale: float = None):
    """Render text as dot-matrix characters starting at (x, y)."""
    if on_color is None:
        on_color = theme.DOT_ON
    if scale is None:
        scale = theme.DOT_SCALE
    off_color = theme.DOT_OFF
    ds = DOT_SIZE * scale
    sp = DOT_SPACING * scale
    cs = CHAR_SPACING * scale

    do_glow = theme.retro_fx
    flicker = theme.is_flicker_frame()

    if flicker:
        on_color = QColor(on_color)
        on_color.setAlphaF(on_color.alphaF() * theme.FLICKER_DIM)

    glow_color = None
    if do_glow:
        glow_color = QColor(on_color)
        glow_color.setAlphaF(min(1.0, on_color.alphaF() * theme.GLOW_BLEED_ALPHA))

    p.setPen(Qt.NoPen)
    cursor_x = x
    for ch in text.upper():
        bitmap = _FONT.get(ch, _FONT.get(' '))

        if do_glow:
            on_set = set()
            for row in range(CHAR_H):
                bits = bitmap[row]
                for col in range(CHAR_W):
                    if (bits >> (CHAR_W - 1 - col)) & 1:
                        on_set.add((col, row))
            glow_set = set()
            for c, r in on_set:
                for dc, dr in _NEIGHBOURS_4:
                    nc, nr = c + dc, r + dr
                    if 0 <= nc < CHAR_W and 0 <= nr < CHAR_H and (nc, nr) not in on_set:
                        glow_set.add((nc, nr))
        else:
            on_set = glow_set = None

        for row in range(CHAR_H):
            bits = bitmap[row]
            for col in range(CHAR_W):
                dx = cursor_x + col * sp
                dy = y + row * sp
                is_on = (bits >> (CHAR_W - 1 - col)) & 1
                if is_on:
                    color = on_color
                elif do_glow and (col, row) in glow_set:
                    color = glow_color
                else:
                    color = off_color
                p.setBrush(color)
                p.drawEllipse(QRectF(dx, dy, ds, ds))
        cursor_x += CHAR_W * sp + cs


def dot_text_width(text: str, scale: float = None) -> float:
    if scale is None:
        scale = theme.DOT_SCALE
    sp = DOT_SPACING * scale
    cs = CHAR_SPACING * scale
    n = len(text)
    if n == 0:
        return 0
    return n * (CHAR_W * sp + cs) - cs


def dot_line_height(scale: float = None) -> float:
    if scale is None:
        scale = theme.DOT_SCALE
    return CHAR_H * DOT_SPACING * scale + LINE_SPACING * scale
